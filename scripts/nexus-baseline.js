#!/usr/bin/env node
'use strict';

/**
 * nexus-baseline.js
 *
 * Snapshot of what this Nexus install provides, so a restructure (moving the
 * repo, splitting core/adapters) can be checked to change nothing:
 *   skills, agents, commands, rules Claude Code loads; hook registrations in
 *   settings.json; user MCP servers (~/.claude.json); what's shared with other
 *   tools (skill links, generated Codex/Gemini agents).
 *
 * Usage:
 *   node nexus-baseline.js                   print the snapshot as JSON
 *   node nexus-baseline.js --out <file>      write it to a file
 *   node nexus-baseline.js --compare <file>  diff against a saved snapshot (exit 1 if different)
 * Env overrides (tests): NEXUS_HOME, NEXUS_CLAUDE_JSON, NEXUS_CLAUDE_SETTINGS, NEXUS_SHARED_SKILLS_DIR,
 *   NEXUS_CODEX_AGENTS_DIR, NEXUS_GEMINI_AGENTS_DIR
 */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { parseFrontmatter } = require('./generate-inventory.js');

const HOME = os.homedir();
const env = process.env;
const ROOT = require('./lib/nexus-home').nexusHome();
const CLAUDE_JSON = env.NEXUS_CLAUDE_JSON || path.join(HOME, '.claude.json');
// Claude Code's settings (hooks) live in ~/.claude, not in the Nexus repo.
const CLAUDE_SETTINGS = env.NEXUS_CLAUDE_SETTINGS || path.join(HOME, '.claude', 'settings.json');
const SHARED_SKILLS = env.NEXUS_SHARED_SKILLS_DIR || path.join(HOME, '.agents', 'skills');
const CODEX_AGENTS = env.NEXUS_CODEX_AGENTS_DIR || path.join(HOME, '.codex', 'agents');
const GEMINI_AGENTS = env.NEXUS_GEMINI_AGENTS_DIR || path.join(HOME, '.gemini', 'agents');
const MARKER = 'GENERATED by Nexus';
const LIST_KEYS = ['skills', 'agents', 'commands', 'rules', 'hooks', 'mcpServers'];

function walk(dir, ext) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    if (e.name.startsWith('.')) return [];
    const full = path.join(dir, e.name);
    if (e.isDirectory()) return walk(full, ext);
    return e.name.endsWith(ext) ? [full] : [];
  });
}

const readJson = (file) => (fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, 'utf8')) : {});
const relSorted = (base, files) => files.map((f) => path.relative(base, f)).sort();

function skills() {
  const dir = path.join(ROOT, 'skills');
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter((n) => fs.existsSync(path.join(dir, n, 'SKILL.md'))).sort();
}

function agents() {
  const names = walk(path.join(ROOT, 'agents'), '.md')
    .map((f) => parseFrontmatter(fs.readFileSync(f, 'utf8')).data.name)
    .filter(Boolean);
  return [...new Set(names)].sort();
}

function hooks() {
  const events = readJson(CLAUDE_SETTINGS).hooks || {};
  const lines = Object.entries(events).flatMap(([event, entries]) => entries.flatMap((entry) =>
    (entry.hooks || []).map((h) => {
      const script = (String(h.command).match(/[A-Za-z0-9_.-]+\.(?:js|sh|py)(?=["'\s]|$)/g) || []).pop();
      return `${event} ${entry.matcher || '*'} -> ${script || String(h.command).slice(0, 60)}`;
    })));
  return [...new Set(lines)].sort();
}

function shared() {
  const count = (dir, ext) => (fs.existsSync(dir)
    ? fs.readdirSync(dir).filter((n) => n.endsWith(ext) && fs.readFileSync(path.join(dir, n), 'utf8').includes(MARKER)).length
    : 0);
  const links = fs.existsSync(SHARED_SKILLS)
    ? fs.readdirSync(SHARED_SKILLS).filter((n) => fs.lstatSync(path.join(SHARED_SKILLS, n)).isSymbolicLink()).length
    : 0;
  return { skillLinks: links, codexAgents: count(CODEX_AGENTS, '.toml'), geminiAgents: count(GEMINI_AGENTS, '.md') };
}

function snapshot() {
  return {
    generatedAt: new Date().toISOString(),
    root: ROOT,
    skills: skills(),
    agents: agents(),
    commands: relSorted(path.join(ROOT, 'commands'), walk(path.join(ROOT, 'commands'), '.md')),
    rules: relSorted(path.join(ROOT, 'rules'), walk(path.join(ROOT, 'rules'), '.md')),
    hooks: hooks(),
    mcpServers: Object.keys(readJson(CLAUDE_JSON).mcpServers || {}).sort(),
    shared: shared(),
  };
}

function compare(saved, current) {
  const lines = [];
  for (const key of LIST_KEYS) {
    const before = new Set(saved[key] || []);
    const after = new Set(current[key] || []);
    const added = [...after].filter((x) => !before.has(x));
    const removed = [...before].filter((x) => !after.has(x));
    if (added.length) lines.push(`${key}: + ${added.join(', ')}`);
    if (removed.length) lines.push(`${key}: - ${removed.join(', ')}`);
  }
  for (const [key, value] of Object.entries(current.shared)) {
    const old = (saved.shared || {})[key];
    if (old !== value) lines.push(`shared.${key}: ${old} -> ${value}`);
  }
  return lines;
}

function main(argv) {
  const current = snapshot();
  const outIdx = argv.indexOf('--out');
  const cmpIdx = argv.indexOf('--compare');
  if (cmpIdx !== -1) {
    const diff = compare(readJson(argv[cmpIdx + 1]), current);
    console.log(diff.length ? diff.join('\n') : 'No differences from the baseline.');
    return diff.length ? 1 : 0;
  }
  const json = `${JSON.stringify(current, null, 2)}\n`;
  if (outIdx !== -1) {
    fs.writeFileSync(argv[outIdx + 1], json);
    console.error(`Baseline written to ${argv[outIdx + 1]}`);
  } else {
    process.stdout.write(json);
  }
  return 0;
}

if (require.main === module) {
  try {
    process.exitCode = main(process.argv.slice(2));
  } catch (err) {
    console.error(`nexus-baseline: ${err.message}`);
    process.exitCode = 2;
  }
}

module.exports = { snapshot, compare };
