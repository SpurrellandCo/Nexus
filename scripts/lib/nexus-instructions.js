'use strict';

/**
 * nexus-instructions.js
 *
 * Puts Nexus's shared instructions into each AI tool's global instruction
 * file, inside a marked block. Text outside the block is the user's own and is
 * never touched; turning a tool off removes only the block.
 *
 *   Claude Code  ~/.claude/CLAUDE.md   import lines (@file): Claude reads the sources live
 *   Codex        ~/.codex/AGENTS.md    content written in (no import support) + rules index
 *   Gemini CLI   ~/.gemini/GEMINI.md   same as Codex
 *
 * Sources: NEXUS.md (shared by every tool), adapters/<tool>/instructions.md
 * (notes for that tool only), rules/ (rules/nexus written in, the rest listed
 * as an index to read when relevant; Claude loads rules/ natively), and
 * ~/.nexus-local/instructions.md (personal, never in the repo).
 *
 * If NEXUS.md doesn't exist (an older checkout), nothing is changed.
 */

const fs = require('fs');
const path = require('path');
const { toolHome } = require('./nexus-home');

const BEGIN_PREFIX = '<!-- BEGIN NEXUS';
const BEGIN = `${BEGIN_PREFIX}: generated by ~/.nexus/scripts/nexus-link.js from ~/.nexus/NEXUS.md `
  + '(edit that, or ~/.nexus-local/instructions.md, instead). Text outside this block is yours and is never touched. -->';
const END = '<!-- END NEXUS -->';

const HOME = toolHome();
const tilde = (p) => (p.startsWith(HOME) ? `~${p.slice(HOME.length)}` : p);
const readTrimmed = (file) => (fs.existsSync(file) ? fs.readFileSync(file, 'utf8').trim() : '');

function realOrSelf(p) {
  try { return fs.realpathSync(p); } catch { return p; }
}

function walkMarkdown(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    if (entry.name.startsWith('.')) return [];
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return walkMarkdown(full);
    return entry.name.endsWith('.md') ? [full] : [];
  });
}

function firstHeading(file) {
  const match = fs.readFileSync(file, 'utf8').match(/^#\s+(.+)$/m);
  return match ? match[1].trim() : path.basename(file, '.md');
}

/** rules/nexus/* written in full; every other rule listed with its title. */
function rulesSection(root) {
  const rulesDir = path.join(root, 'rules');
  const files = walkMarkdown(rulesDir).sort();
  const isNexusRule = (f) => path.relative(rulesDir, f).startsWith(`nexus${path.sep}`);
  const parts = files.filter(isNexusRule).map((f) => fs.readFileSync(f, 'utf8').trim());
  const indexed = files.filter((f) => !isNexusRule(f));
  if (indexed.length) {
    parts.push(`## Coding standards\n\nMore standards live in \`${tilde(rulesDir)}\`. `
      + 'Before writing code, read the ones that match your task:\n\n'
      + indexed.map((f) => `- \`${path.relative(root, f)}\`: ${firstHeading(f)}`).join('\n'));
  }
  return parts.join('\n\n');
}

function render(tool, { root, localFile }) {
  const nexusMd = path.join(root, 'NEXUS.md');
  const adapter = path.join(root, 'adapters', tool, 'instructions.md');
  if (tool === 'claude') {
    return [nexusMd, adapter, localFile].filter((f) => fs.existsSync(f)).map((f) => `@${f}`).join('\n');
  }
  const local = readTrimmed(localFile);
  return [
    readTrimmed(nexusMd),
    readTrimmed(adapter),
    rulesSection(root),
    local ? `## Personal instructions\n\n${local}` : '',
  ].filter(Boolean).join('\n\n');
}

function splitBlock(text) {
  const start = text.indexOf(BEGIN_PREFIX);
  const end = text.indexOf(END);
  if (start === -1 || end === -1 || end < start) return null;
  const after = text.slice(end + END.length).replace(/^\n+/, '');
  return { before: text.slice(0, start), after };
}

function isLinkIntoRoot(file, root) {
  const st = fs.lstatSync(file, { throwIfNoEntry: false });
  if (!st || !st.isSymbolicLink()) return false;
  return realOrSelf(file).startsWith(realOrSelf(root) + path.sep);
}

function upsertBlock(file, body, { root, replaceCopies, backup }) {
  const block = `${BEGIN}\n\n${body.trim()}\n\n${END}\n`;
  if (isLinkIntoRoot(file, root)) fs.unlinkSync(file); // older layout linked CLAUDE.md into the repo
  const st = fs.lstatSync(file, { throwIfNoEntry: false });
  if (st && st.isSymbolicLink()) return 'skipped-link';
  const current = st ? fs.readFileSync(file, 'utf8') : null;
  const parts = current === null ? null : splitBlock(current);
  let next;
  let action = 'written';
  if (current === null) next = block;
  else if (parts) next = `${parts.before}${block}${parts.after ? `\n${parts.after}` : ''}`;
  else if (replaceCopies) { backup(file); next = block; action = 'replaced'; }
  else next = `${block}\n${current}`;
  if (next === current) return null;
  fs.writeFileSync(file, next);
  return action;
}

function removeBlock(file) {
  const st = fs.lstatSync(file, { throwIfNoEntry: false });
  if (!st || st.isSymbolicLink()) return null;
  const parts = splitBlock(fs.readFileSync(file, 'utf8'));
  if (!parts) return null;
  const rest = `${parts.before}${parts.after}`;
  if (rest.trim() === '') fs.rmSync(file);
  else fs.writeFileSync(file, rest);
  return 'removed';
}

/**
 * targets: [{ tool, label, file }]. Returns [{ label, file, action }] for files
 * that changed (action: written | replaced | removed | skipped-link).
 */
function syncInstructions({ tools, root, targets, localFile, replaceCopies, backup }) {
  if (!fs.existsSync(path.join(root, 'NEXUS.md'))) return [];
  const results = [];
  for (const { tool, label, file } of targets) {
    if (!fs.existsSync(path.dirname(file))) continue; // tool not installed
    const action = tools.includes(tool)
      ? upsertBlock(file, render(tool, { root, localFile }), { root, replaceCopies, backup })
      : removeBlock(file);
    if (action) results.push({ label, file, action });
  }
  return results;
}

module.exports = { syncInstructions, render, BEGIN_PREFIX, END };
